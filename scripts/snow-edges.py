#!/usr/bin/env python3
# Writes Sunrise's five hand-cut snow edges into Swift (docs/SUNRISE-PLAN.md, "The snow edges").
#
# The edges are firn-site's own (design/firn-sunrise/tools/snow-edges.json), copied into brand/sunrise/.
# Each has 121 points: x in percent of the width, y from 0 (the edge's highest point) to 1 (its lowest).
# The Swift file stores x as a fraction (0 to 1) so drawing is x × width and y × the layer's edge height.
#
# Run by hand after copying a new snow-edges.json from the site, never at build time:
#   python3 scripts/snow-edges.py
import json
import pathlib

REPO = pathlib.Path(__file__).resolve().parent.parent
SOURCE = REPO / "brand" / "sunrise" / "snow-edges.json"
OUT = REPO / "Shared" / "Sunrise" / "SnowEdges.swift"
LAYERS = ["l1", "l2", "l3", "l4", "l5"]  # l1 is the surface, l5 the deepest


def number(v: float) -> str:
    text = f"{v:.5f}".rstrip("0").rstrip(".")
    return text if text not in ("", "-0") else "0"


def main() -> None:
    edges = json.loads(SOURCE.read_text())
    lines = [
        "// Generated by scripts/snow-edges.py from brand/sunrise/snow-edges.json. Don't edit by hand:",
        "// copy a new snow-edges.json from firn-site, then run the script again.",
        "//",
        "// Sunrise's five hand-cut snow edges, surface first. Each point's x is a fraction of the width (0 to 1)",
        "// and its y runs from 0 (the edge's highest point) to 1 (its lowest), times the layer's edge height.",
        "// Joined with straight lines, as the site does.",
        "",
        "import CoreGraphics",
        "",
        "enum SnowEdges {",
        "    /// The five edges, surface (layer 1) first.",
        "    static let layers: [[CGPoint]] = [" + ", ".join(LAYERS) + "]",
        "",
    ]
    for name in LAYERS:
        points = edges[name]
        if len(points) < 2 or points[0][0] != 0 or points[-1][0] != 100:
            raise SystemExit(f"{name}: expected points from x 0 to 100")
        for x, y in points:
            if not (0 <= x <= 100 and 0 <= y <= 1):
                raise SystemExit(f"{name}: point out of range: {x}, {y}")
        lines.append(f"    private static let {name}: [CGPoint] = [")
        for x, y in points:
            lines.append(f"        CGPoint(x: {number(x / 100)}, y: {number(y)}),")
        lines.append("    ]")
        lines.append("")
    lines[-1] = "}"
    OUT.write_text("\n".join(lines) + "\n")
    print(f"Wrote {OUT.relative_to(REPO)} ({sum(len(edges[n]) for n in LAYERS)} points)")


if __name__ == "__main__":
    main()
